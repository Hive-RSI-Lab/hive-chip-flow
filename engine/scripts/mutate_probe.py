#!/usr/bin/env python
"""mutate_probe.py - the two sims check_mutate.py runs to say WHY a mutant
survived (#82c). One process per run, so check_mutate can bound each with a
timeout and run several at once.

    mutate_probe.py cover --tb DIR --top T --seed N --work DIR --src SRC...
        The visible tb/ suite over Verilator with --coverage-line, on the
        unmutated RTL. Writes WORK/coverage.info (lcov: `DA:<line>,<hits>`
        per source line Verilator counts). A survivor whose RTL lines all
        read 0 there was never activated: no test reached its code.

    mutate_probe.py trace --tb DIR --top T --seed N --work DIR
                    --netlist FILE --watch p1,p2 --outputs o1,o2
        The visible tb/ suite over Icarus on one netlist (the unmutated
        design or a mutant), with a monitor compiled in beside it that
        writes WORK/trace.txt: one line `<t_ps> <o1> <o2> ...` at the end of
        every time step in which any watched port (inputs and outputs)
        changed. The same seed on the original and on a mutant drives the
        same stimulus, so the two traces match until the mutant's change
        reaches an output port.

Both print one JSON line: {"ok": true, ...} or {"ok": false, "error": ...},
and exit 0 either way: check_mutate reads the line.
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
ENGINE = SCRIPTS.parent
REPO = ENGINE.parent
sys.path.insert(0, str(ENGINE / "lib"))
sys.path.insert(0, str(SCRIPTS))
import cocotblib  # noqa: E402
from mutate_runner import regroup_flops  # noqa: E402

EDA_BIN = REPO / "bin" / "eda"
MODULE = "cf_ptrace__"
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_$]*\Z")


def tracer_verilog(top: str, watch: list[str], outputs: list[str],
                   path: Path) -> str:
    """A root module that $fstrobes the top's output ports to `path`
    whenever any watched port changes; $realtime is in the run's 1ns
    timescale, so *1000 is integer ps."""
    sens = " or ".join(f"{top}.{p}" for p in watch)
    fmt = " ".join(["%0d"] + ["%b"] * len(outputs))
    vals = ", ".join(f"{top}.{p}" for p in outputs)
    return f"""\
// generated by engine/scripts/mutate_probe.py (#82c)
module {MODULE};
  integer fd;
  // $fstrobe takes only plain signals (Icarus), so the time goes
  // through a variable first
  reg [63:0] t_ps;
  initial fd = $fopen("{path}", "w");
  always @({sens}) begin
    t_ps = $realtime * 1000.0;
    $fstrobe(fd, "{fmt}", t_ps, {vals});
  end
endmodule
"""


def cover(args) -> dict:
    from cocotb_tools.runner import get_runner
    work = Path(args.work).resolve()
    build = work / "build"
    dat = work / "coverage.dat"
    info = work / "coverage.info"
    tb = Path(args.tb).resolve()
    log = str(work / "cover.log")
    runner = get_runner("verilator")
    runner.build(sources=[str(Path(s).resolve()) for s in args.src],
                 hdl_toplevel=args.top, build_dir=str(build), always=True,
                 build_args=["--coverage-line"], log_file=log)
    try:
        runner.test(hdl_toplevel=args.top,
                    test_module=cocotblib.test_modules(tb),
                    test_dir=str(tb), build_dir=str(build),
                    results_xml=str(work / "results.xml"), log_file=log,
                    seed=args.seed,
                    plusargs=[f"+verilator+coverage+file+{dat}"])
    except SystemExit:
        pass
    if not dat.is_file():
        return {"ok": False, "error": "the coverage run wrote no "
                "coverage.dat"}
    proc = subprocess.run(
        [str(EDA_BIN), "verilator_coverage", "--write-info", str(info),
         str(dat)], capture_output=True, text=True, encoding="utf-8",
        errors="replace")
    if proc.returncode != 0 or not info.is_file():
        return {"ok": False, "error": "verilator_coverage --write-info "
                f"exited {proc.returncode}: "
                f"{(proc.stderr or proc.stdout)[-500:]}"}
    return {"ok": True, "info": str(info)}


def trace(args) -> dict:
    work = Path(args.work).resolve()
    work.mkdir(parents=True, exist_ok=True)
    netlist = work / "netlist.v"
    netlist.write_text(regroup_flops(
        Path(args.netlist).read_text(encoding="utf-8")), encoding="utf-8")
    watch = [p for p in args.watch.split(",") if IDENT.match(p)]
    outputs = [p for p in args.outputs.split(",") if IDENT.match(p)]
    if not watch or not outputs:
        return {"ok": False, "error": "no port to watch"}
    out = work / "trace.txt"
    mon = work / f"{MODULE}.v"
    mon.write_text(tracer_verilog(args.top, watch, outputs, out),
                   encoding="utf-8")
    tb = Path(args.tb).resolve()
    xml = cocotblib.run_cocotb(
        work / "build", tb, [netlist, mon], args.top,
        cocotblib.test_modules(tb), work / "results.xml", seed=args.seed,
        build_args=["-s", MODULE])
    parsed = cocotblib.parse_results_xml(xml)
    if not out.is_file():
        return {"ok": False, "error": "the traced run wrote no trace"}
    return {"ok": True, "trace": str(out), "outputs": outputs,
            "passed": bool(parsed) and all(r["passed"]
                                           for r in parsed.values())}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("mode", choices=("cover", "trace"))
    ap.add_argument("--tb", required=True)
    ap.add_argument("--top", required=True)
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--work", required=True)
    ap.add_argument("--netlist")
    ap.add_argument("--watch", default="")
    ap.add_argument("--outputs", default="")
    ap.add_argument("--src", nargs="*", default=[])
    args = ap.parse_args(argv)
    try:
        res = cover(args) if args.mode == "cover" else trace(args)
    except Exception as exc:  # noqa: BLE001 - reported, not raised
        res = {"ok": False, "error": f"{type(exc).__name__}: {exc}"}
    print(json.dumps(res))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
