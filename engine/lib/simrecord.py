"""simrecord.py - what a passing test's outputs did, kept so a later failure
of the same test can name the first edge it went another way (#360).

check_sim compiles one more Verilog root module beside the design (`-s`,
as xmonlib's): on every rising edge of the clock it reads the top's output
ports by hierarchical name - their values once that edge's update has
settled, what a bench reads after `await RisingEdge` - and writes a line
to its own file only when one of them differs from the last line. A green run writes
no dump: one short text line per edge where an output moved.

After the run, each test's slice of that file (results.xml gives its
sim_time_start and _stop) becomes a step list over the time since the test
started. A test that passed is saved as log/sim_record/<test>@<seed>.json
with the testbench digest, the RTL digest it passed on and the output
names; a test that failed is compared with the saved one for the same test
and seed, and the first time an output differs is its `first_divergence`.
A record from another testbench version, another output list or another
clock is not used: no field, no error. It never changes a verdict.

The record lives beside log/sim_build/, not inside it: check_sim empties
sim_build at the start of every run, and the record is there to outlive
the run that wrote it.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

MODULE = "cf_simrec__"
RECORD_SUBDIR = "log/sim_record"
VERSION = 1
_IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_$]*\Z")
_LINE = re.compile(r"(\d+)((?: \S+)+)\Z")


def plan(spec: dict) -> dict:
    """{"on": True, clock, outputs: [(name, width)]} or {"on": False, why}.
    The clock is the one xmonlib watches (clock.primary, the only clock
    domain, else a 1-bit input named clk)."""
    import xmonlib
    inputs = xmonlib._inputs(spec)
    clk = xmonlib._clock(spec, inputs)
    if clk is None:
        return {"on": False, "why": "no 1-bit clock input found (clock."
                "domains / a port named clk)"}
    outs = [(str(n), int(p.get("width") or 1))
            for n, p in (spec.get("ports") or {}).items()
            if isinstance(p, dict) and p.get("dir") == "output"
            and _IDENT.match(str(n))]
    if not outs:
        return {"on": False, "why": "the spec has no output port"}
    return {"on": True, "clock": clk, "outputs": outs}


def monitor_verilog(p: dict, hdl_top: str, out_file: Path) -> str:
    sigs = [f"{hdl_top}.{n}" for n, _ in p["outputs"]]
    total = sum(w for _, w in p["outputs"])
    cat = "{" + ", ".join(sigs) + "}"
    fmt = " ".join("%b" for _ in sigs)
    path = str(Path(out_file).resolve()).replace("\\", "\\\\") \
        .replace('"', '\\"')
    # $realtime is in this module's timescale (the run's 1ns): *1000 is ps.
    # `tick` flips in the edge's nonblocking region, so the block below
    # runs after the design's own nonblocking updates at that edge; its #0
    # then lets the continuous assigns they drive settle. The line carries
    # the edge's time and the values after it.
    return f"""\
// generated by engine/lib/simrecord.py (#360): the top's outputs at each
// rising clock edge, one line whenever one of them changed.
module {MODULE};
  integer fd;
  reg [{total - 1}:0] last;
  reg first = 1'b1;
  reg tick = 1'b0;
  initial fd = $fopen("{path}", "w");
  always @(posedge {hdl_top}.{p['clock']}) tick <= ~tick;
  always @(tick) begin
    #0;
    if (first || {cat} !== last) begin
      $fdisplay(fd, "%0d {fmt}", $realtime * 1000.0, {", ".join(sigs)});
      $fflush(fd);
      last = {cat};
      first = 1'b0;
    end
  end
endmodule
"""


def write_monitor(spec: dict, hdl_top: str, out_dir: Path):
    """(plan, extra sources, extra build args, the file the run writes)."""
    p = plan(spec)
    if not p["on"]:
        return p, [], [], None
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / "outputs.txt"
    src = out_dir / f"{MODULE}.v"
    src.write_text(monitor_verilog(p, hdl_top, out_file), encoding="utf-8")
    return p, [src], ["-s", MODULE], out_file


def read_changes(path: Path, n: int) -> list[tuple[int, list[str]]]:
    """[(t_ps, [bits per output])] from the monitor's file; [] if none."""
    out = []
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return out
    for line in text.splitlines():
        m = _LINE.match(line.strip())
        if not m:
            continue
        vals = m.group(2).split()
        if len(vals) == n:
            out.append((int(m.group(1)), vals))
    return out


def take(path: Path, n: int) -> list[tuple[int, list[str]]]:
    """read_changes, then remove the file: the next run on the same build
    (an extra seed) starts its own."""
    changes = read_changes(path, n)
    try:
        Path(path).unlink()
    except OSError:
        pass
    return changes


def slice_test(changes, start_ns: float | None, stop_ns: float | None):
    """One test's outputs as [[t_ps since its start, [bits]]]: the values at
    its first edge's sampling (the last line at or before its start), then
    every change up to its stop. None without both times."""
    if start_ns is None or stop_ns is None:
        return None
    t0 = int(round(start_ns * 1000.0))
    t1 = int(round(stop_ns * 1000.0))
    before = None
    rows = []
    for t, vals in changes:
        if t <= t0:
            before = vals
        elif t <= t1:
            rows.append([t - t0, vals])
    if before is not None:
        rows.insert(0, [0, before])
    return rows


def digest(path: Path) -> str:
    """sha256 of a directory's files (paths and bytes)."""
    h = hashlib.sha256()
    path = Path(path)
    for p in sorted(q for q in path.rglob("*") if q.is_file()):
        h.update(p.relative_to(path).as_posix().encode() + b"\0")
        h.update(p.read_bytes() + b"\0")
    return h.hexdigest()


def record_path(ws: Path, test: str, seed: int) -> Path:
    return Path(ws) / RECORD_SUBDIR / f"{test}@{seed}.json"


def save(ws: Path, test: str, seed: int, p: dict, tb: str, rtl: str,
         rows, duration_ps: int) -> None:
    path = record_path(ws, test, seed)
    path.parent.mkdir(parents=True, exist_ok=True)
    body = {"version": VERSION, "test": test, "seed": seed, "tb": tb,
            "rtl": rtl, "clock": p["clock"],
            "outputs": [[n, w] for n, w in p["outputs"]],
            "duration_ps": int(duration_ps), "rows": rows}
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps(body, separators=(",", ":")) + "\n",
                   encoding="utf-8")
    tmp.replace(path)


def load(ws: Path, test: str, seed: int, p: dict, tb: str) -> dict | None:
    """The saved record for test at seed when it was made by this
    testbench version, over the same clock and outputs; else None."""
    try:
        body = json.loads(record_path(ws, test, seed).read_text(
            encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(body, dict) or body.get("version") != VERSION \
            or body.get("tb") != tb or body.get("clock") != p["clock"] \
            or body.get("outputs") != [[n, w] for n, w in p["outputs"]] \
            or not isinstance(body.get("rows"), list):
        return None
    return body


def _at(rows, t):
    """The values in effect at t (the last row at or before t), or None."""
    cur = None
    for rt, vals in rows:
        if rt > t:
            break
        cur = vals
    return cur


def first_divergence(was_rows, now_rows, outputs,
                     until_ps: int) -> dict | None:
    """The first edge since the test's start, up to until_ps (the shorter
    of the two runs), after which an output differs: {"test_ns", "signal",
    "was", "now"} (values as wavelib.to_text shows them), or None when
    they agree that long."""
    import wavelib
    times = sorted({t for t, _ in was_rows} | {t for t, _ in now_rows})
    end = until_ps
    for t in times:
        if t > end:
            break
        a, b = _at(was_rows, t), _at(now_rows, t)
        if a is None or b is None or a == b:
            continue
        for (name, width), x, y in zip(outputs, a, b):
            if x != y:
                return {"test_ns": t / 1000.0, "signal": name,
                        "was": wavelib.to_text(x, width),
                        "now": wavelib.to_text(y, width)}
    return None
