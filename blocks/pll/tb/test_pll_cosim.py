"""Top-level cosim bench for the charge-pump PLL (msde `cosim` gate).

The released RTL (ihsan_sa_pll, compiled by Icarus) closes the loop through
the analog cell simulated by ngspice inside cocotbext-ams's
MixedSignalBridge: pfd_up/pfd_dn/pll_en/cp_trim0/cp_trim1 drive ngspice
sources, vco_out comes back as the digitized ngspice waveform and clocks the
real prescaler and divider. cosim_bench.json picks the analog model:
  - "transistor": pll_analog_tr.sp, the real netlist + PDK models + sizing
  - "ideal":      pll_analog_ideal.sp, generated by calibrate_analog.py from
                  measurements of that same netlist at tt_27c

Operating point: the brief's nominal point, f_ref = 6.25 MHz, n_sel = 2
(P*N = 16, f_vco = 100 MHz), cp_trim = 00, obs_sel = 0, tt.

Measures (reports/cosim_measures.json, written before any assertion), with
bounds from the specs (pll_cosim.bounds.json):
  lock_time_us          pll_en rising -> first lock rising       (<= 50 us,
                        digital REQ-LOOP-LOCK / analog spec "Out of scope")
  lock_drops_after_lock lock falls after the first rise           (0)
  fb_period_rel_err     |mean clk_fb period - T_ref| / T_ref over the
                        final 10 us                               (<= 0.1 %)
  vco_period_rel_err    |mean vco_out period - T_ref/16| / (T_ref/16),
                        same window                               (<= 0.1 %)
  vctrl_pp_last_10us_mv peak-to-peak of the loop filter node over the
                        final 10 us                               (<= 20 mV)
plus digital_toggles / edge_times_ns (every clk_fb rising edge) and
spice_time_reached_ns for check_cosim.py's evidence checks, and unbounded
context (frequencies, final vctrl, static phase offset, run time).
"""
from __future__ import annotations

import json
import math
import os
import sys
import time
from pathlib import Path

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import FallingEdge, RisingEdge, Timer
from cocotbext.ams import AnalogBlock, DigitalPin, MixedSignalBridge
from cocotbext.ams._ngspice import NgspiceInterface

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import pll_tb_common as C  # noqa: E402

LIBNGSPICE = os.environ["LIBNGSPICE_PATH"]
REPORTS = HERE.parent / "reports"

T_REF_NS = 1e9 / C.F_REF_HZ                      # 160 ns
PN = C.P * C.N_SEL                               # 16
T_VCO_NS = T_REF_NS / PN                         # 10 ns
RELEASE_NS = 320.0                               # rst_n / pll_en_in release
WINDOW_NS = 10_000.0                             # final settling window
# Run length: lock is expected within a few us at this point (brief: ~3 us
# small-signal + slewing), the bound is 50 us; the run must leave a full
# 10 us window after lock. Overridable for exploration only.
DURATION_NS = float(os.environ.get("PLL_COSIM_DURATION_NS", "30000"))
# Bridge fallback sync: bounds both the D->A latency of a reference-edge
# PFD transition (applied at the next sync) and how early the bridge forces
# a vco_out edge (at the previous sync) to 1 ns, 0.6 % of T_ref.
MAX_SYNC_NS = 1.0
# A sync point this long after every clk rising edge (SyncSafeNgspice).
REF_SYNC_LAG_NS = 0.002

# extra nodes saved only for a debug analog VCD (PLL_COSIM_ANALOG_VCD)
DEBUG_NODES = [n.strip() for n in os.environ.get(
    "PLL_COSIM_DEBUG_NODES", "").split(",") if n.strip()]

MODELS = {
    # kind: (netlist, subckt, tran_step, extra model lines?)
    "transistor": ("pll_analog_tr.sp", "pll_analog_cosim", "50p", True),
    "ideal": ("pll_analog_ideal.sp", "pll_analog_ideal", "100p", False),
}


class SyncSafeNgspice(NgspiceInterface):
    """cocotbext-ams's sync callback clamps ngspice's next step to
    (next_sync_time - ckttime). When ngspice's own time lands a float
    rounding short of the sync point (e.g. 3.9999999999999996e-09 against
    4e-09) that remainder is ~1e-25 s, the clamp hands ngspice a step far
    below its minimum and the transient aborts with "Timestep too small"
    (docs/spikes/dcosim.md's open shared-library quirk). A remainder under
    SYNC_EPS_S is treated as having reached the sync point; nothing else in
    the callback changes.

    Reference-edge sync points: a digital change only reaches ngspice at
    the next sync point, so a PFD edge launched by a clk rising edge (a
    cocotb Clock, between syncs) would otherwise reach the pump up to
    max_sync_interval late, a random 0..1 ns per cycle that the real
    circuit does not have. When ref_grid = (t0_s, period_s, lag_s) is set,
    a sync is also scheduled lag_s after every reference rising edge: by
    then cocotb has run the edge, the PFD and the bridge's input monitors,
    so ngspice resumes with UP/DN already in its sources (lag_s = 2 ps)."""

    SYNC_EPS_S = 1e-15
    ref_grid: tuple[float, float, float] | None = None

    def _on_get_sync_data(self, ckttime, p_delta, old_delta, redostep,
                          ident, location, userdata):
        if not self._simulation_done and self.ref_grid is not None:
            t0, per, lag = self.ref_grid
            k = math.floor((ckttime - t0 - lag) / per + 1e-9) + 1
            t_next = t0 + lag + k * per
            if t_next - ckttime <= self.SYNC_EPS_S:
                t_next += per
            if t_next < self._next_sync_time:
                self._next_sync_time = t_next
        if (not self._simulation_done
                and 0.0 < self._next_sync_time - ckttime < self.SYNC_EPS_S):
            self._next_sync_time = ckttime
        return super()._on_get_sync_data(ckttime, p_delta, old_delta,
                                         redostep, ident, location, userdata)


class Bridge(MixedSignalBridge):
    """MixedSignalBridge with two bench-side fixes, nothing else changed:
    - SyncSafeNgspice as its simulator (above);
    - an analog output is written to the HDL only when its digitized value
      changes, as a plain value on a reg (pll_cosim_top's vco_out), instead
      of a vpi Force on every sync point. Re-forcing a net at every 1 ns
      sync crashed vvp (SIGSEGV in the simulator thread, no Python frame)
      after a few hundred to a thousand forces, with the ideal and the
      transistor model alike; with write-on-change the same run completes.
      The value written and the time it is written at are the stock
      bridge's own (digitized at the sync point, applied before cocotb
      advances), so the timing semantics are unchanged."""

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self._written: dict[str, int] = {}

    ref_grid: tuple[float, float, float] | None = None

    def _create_simulator(self, simulator):
        if simulator == "ngspice":
            sim = SyncSafeNgspice(self._simulator_lib)
            sim.ref_grid = self.ref_grid
            return sim
        return super()._create_simulator(simulator)

    def _read_analog_outputs(self, block):
        outs = self._block_output_nodes.get(block.name, {})
        for name, pin in block.digital_pins.items():
            if pin.direction != "output" or not outs.get(name):
                continue
            volts = [self._sim.get_node_voltage(n) for n in outs[name]]
            prev = self._sim._prev_digital_values.get(name)
            val = pin.analog_to_digital(volts, prev_value=prev)
            if self._written.get(name) != val:
                self._resolve_signal(block.name, name).value = val
                self._written[name] = val

    def _release_outputs(self, block):
        pass  # nothing is forced, so nothing to release


class Edges:
    """Rising/falling edge times (ns) of a 1-bit signal."""

    def __init__(self, sig, falls=False):
        self.sig = sig
        self.rises: list[float] = []
        self.falls: list[float] = []
        cocotb.start_soon(self._rise())
        if falls:
            cocotb.start_soon(self._fall())

    async def _rise(self):
        while True:
            await RisingEdge(self.sig)
            self.rises.append(cocotb.utils.get_sim_time(unit="ns"))

    async def _fall(self):
        while True:
            await FallingEdge(self.sig)
            self.falls.append(cocotb.utils.get_sim_time(unit="ns"))


def vco_short(vco, t_en, min_ns=2.0):
    """vco_out high or low intervals shorter than min_ns (a fifth of the
    10 ns nominal period) after the VCO has run 2 us: [start_ns, width_ns]."""
    if t_en is None:
        return None
    ev = sorted([(t, 1) for t in vco.rises] + [(t, 0) for t in vco.falls])
    out = []
    for (t0, _), (t1, _) in zip(ev, ev[1:]):
        if t0 > t_en + 2000 and t1 - t0 < min_ns:
            out.append([round(t0, 3), round(t1 - t0, 3)])
    return out


def mean_period(ts: list[float]) -> float | None:
    return (ts[-1] - ts[0]) / (len(ts) - 1) if len(ts) >= 2 else None


def rel_err(got: float | None, want: float) -> float | None:
    return None if got is None else abs(got - want) / want


@cocotb.test()
async def test_pll_lock_nominal(dut):
    meta = C.bench_meta()
    # PLL_COSIM_KIND lets run_layers.py run the other model as a separate
    # layer; its measures then go to cosim_measures_<kind>.json, never to
    # the gate's own cosim_measures.json (which always follows
    # cosim_bench.json).
    override = os.environ.get("PLL_COSIM_KIND")
    kind = override or meta["analog_kind"]
    netlist, subckt, tran_step, real_cell = MODELS[kind]
    out_name = (f"cosim_measures_{kind}.json" if override
                else "cosim_measures.json")
    assert override or meta["analog_netlist"] == netlist, (
        f"cosim_bench.json names {meta['analog_netlist']} but analog_kind "
        f"{kind!r} runs {netlist}")
    extra = list(C.model_lines()) if real_cell else []
    extra += [".save v(x1.vctrl)", ".options reltol=1e-3"]
    if os.environ.get("PLL_COSIM_ANALOG_VCD"):            # debug only
        extra += [".save " + " ".join(f"v({n})" for n in DEBUG_NODES)]

    pin = dict(vdd=C.VDD, vss=0.0)
    block = AnalogBlock(
        name="pll_analog",
        spice_file=str(HERE / netlist),
        subcircuit=subckt,
        digital_pins={
            # interface.yaml names; d2a = bridge "input", a2d = "output"
            "pfd_up": DigitalPin(direction="input", **pin),
            "pfd_dn": DigitalPin(direction="input", **pin),
            "pll_en": DigitalPin(direction="input", **pin),
            "cp_trim0": DigitalPin(direction="input", **pin),
            "cp_trim1": DigitalPin(direction="input", **pin),
            "vco_out": DigitalPin(direction="output", **pin),
        },
        vdd=C.VDD, vss=0.0, tran_step=tran_step, extra_lines=extra,
    )

    # tile inputs: reset held, PLL disabled, nominal point
    dut.rst_n.value = 0
    dut.pll_en_in.value = 0
    dut.n_sel.value = C.N_SEL
    dut.obs_sel.value = 0
    dut.cp_trim_in.value = 0
    dut.clk.value = 0
    await Timer(1, unit="ns")

    bridge = Bridge(dut, [block], max_sync_interval_ns=MAX_SYNC_NS,
                               simulator_lib=LIBNGSPICE)
    t_clk0 = cocotb.utils.get_sim_time(unit="ns")   # first clk rising edge
    cocotb.start_soon(Clock(dut.clk, T_REF_NS, unit="ns").start())
    bridge.ref_grid = (t_clk0 * 1e-9, T_REF_NS * 1e-9, REF_SYNC_LAG_NS * 1e-9)
    ref = Edges(dut.clk)
    fb = Edges(dut.clk_fb)
    vco = Edges(dut.vco_out, falls=True)
    en = Edges(dut.pll_en)
    lock = Edges(dut.lock, falls=True)
    vctrl: list[tuple[float, float]] = []

    async def sample_vctrl():
        sim = None
        while True:
            await Timer(5, unit="ns")
            sim = sim or bridge._sim
            if sim is None:
                continue
            v = sim._node_voltages.get("x1.vctrl")
            if v is not None:
                vctrl.append((cocotb.utils.get_sim_time(unit="ns"), v))

    vctrl_ref: list[tuple[float, float]] = []

    async def sample_vctrl_at_ref():
        """vctrl just after each ref rising edge (the 2 ps sync point):
        once per cycle at a fixed phase, so per-cycle pump ripple is not in
        it - reported for context, unbounded."""
        while True:
            await RisingEdge(dut.clk)
            await Timer(3, unit="ps")
            if bridge._sim is not None:
                v = bridge._sim._node_voltages.get("x1.vctrl")
                if v is not None:
                    vctrl_ref.append((cocotb.utils.get_sim_time(unit="ns"), v))

    async def release():
        await Timer(RELEASE_NS - 1, unit="ns")
        dut.rst_n.value = 1
        dut.pll_en_in.value = 1

    cocotb.start_soon(sample_vctrl())
    cocotb.start_soon(sample_vctrl_at_ref())
    cocotb.start_soon(release())

    wall0 = time.monotonic()
    err = None
    try:
        vcd = os.environ.get("PLL_COSIM_ANALOG_VCD")  # debug only
        await bridge.start(duration_ns=DURATION_NS, analog_vcd=vcd or None,
                           vcd_nodes=["x1.vctrl"] + DEBUG_NODES if vcd else None)
    except Exception as exc:  # noqa: BLE001 - recorded, re-raised below
        err = exc
    finally:
        wall_s = time.monotonic() - wall0
        spice_ns = bridge._last_sync_spice_time * 1e9
        t_end = min(spice_ns, cocotb.utils.get_sim_time(unit="ns"))
        t_en = en.rises[0] if en.rises else None
        t_lock = lock.rises[0] if lock.rises else None
        lock_time_us = ((t_lock - t_en) / 1000.0
                        if t_lock is not None and t_en is not None else None)
        drops = (sum(1 for t in lock.falls if t > t_lock)
                 if t_lock is not None else None)
        # final window: the last 10 us, never reaching back before lock
        w0 = t_end - WINDOW_NS
        if t_lock is not None:
            w0 = max(w0, t_lock)
        fb_w = [t for t in fb.rises if w0 <= t <= t_end]
        vco_w = [t for t in vco.rises if w0 <= t <= t_end]
        vc_w = [v for t, v in vctrl if w0 <= t <= t_end]
        vr_w = [v for t, v in vctrl_ref if w0 <= t <= t_end]
        fb_t = mean_period(fb_w)
        vco_t = mean_period(vco_w)
        ref_w = [t for t in ref.rises if w0 <= t <= t_end]
        # static phase offset: clk_fb rise minus the nearest clk rise
        offs = []
        for t in fb_w:
            near = min(ref_w, key=lambda r: abs(r - t)) if ref_w else None
            if near is not None:
                offs.append(t - near)
        locked_window = t_lock is not None and w0 >= t_lock
        measures = {
            "analog_kind": kind,
            "analog_netlist": netlist,
            "operating_point": {"f_ref_hz": C.F_REF_HZ, "n_sel": C.N_SEL,
                                "p_times_n": PN, "f_vco_target_hz": C.F_REF_HZ * PN,
                                "cp_trim": "00", "corner": "tt_27c"},
            "lock_time_us": lock_time_us,
            "lock_drops_after_lock": drops,
            "fb_period_rel_err": rel_err(fb_t, T_REF_NS),
            "vco_period_rel_err": rel_err(vco_t, T_VCO_NS),
            "vctrl_pp_last_10us_mv": ((max(vc_w) - min(vc_w)) * 1000.0
                                      if len(vc_w) >= 2 and locked_window else None),
            "vctrl_pp_at_ref_edges_last_10us_mv": ((max(vr_w) - min(vr_w)) * 1000.0
                                                   if len(vr_w) >= 2 else None),
            "vco_min_period_ns_after_en": min(
                (b - a for a, b in zip(vco.rises, vco.rises[1:])
                 if t_en is not None and a > t_en + 2000), default=None),
            "vco_short_pulses_after_en": vco_short(vco, t_en),
            "vco_odd_periods_window": [
                [round(a, 3), round(b - a, 3)]
                for a, b in zip(vco.rises, vco.rises[1:])
                if w0 <= a <= t_end and not 9.0 <= b - a <= 11.0][:50],
            "fb_freq_hz": 1e9 / fb_t if fb_t else None,
            "vco_freq_hz": 1e9 / vco_t if vco_t else None,
            "vctrl_final_v": vctrl[-1][1] if vctrl else None,
            "vctrl_mean_window_v": sum(vc_w) / len(vc_w) if vc_w else None,
            "static_phase_offset_ns": sum(offs) / len(offs) if offs else None,
            "window_ns": [w0, t_end],
            "window_after_lock": locked_window,
            "pll_en_rise_ns": t_en,
            "lock_rise_ns": t_lock,
            "lock_rises": len(lock.rises),
            "duration_ns": DURATION_NS,
            "max_sync_interval_ns": MAX_SYNC_NS,
            "wall_time_s": wall_s,
            "bridge_error": repr(err) if err else None,
            "digital_toggles": len(fb.rises),
            "edge_times_ns": list(fb.rises),
            "spice_time_reached_ns": spice_ns,
            "vctrl_trace_us_v": [[round(t / 1000, 4), round(v, 5)]
                                 for t, v in vctrl[::20]],
        }
        REPORTS.mkdir(parents=True, exist_ok=True)
        (REPORTS / out_name).write_text(
            json.dumps(measures, indent=1), encoding="utf-8")
        await bridge.stop()

    if err is not None:
        raise err
    assert t_en is not None, "pll_en never rose"
    assert lock_time_us is not None, "lock never asserted"
    assert lock_time_us <= 50, f"lock took {lock_time_us:.2f} us (> 50 us)"
    assert drops == 0, f"lock dropped {drops} time(s) after it first rose"
    assert locked_window, "the final 10 us window does not start after lock"
    assert measures["fb_period_rel_err"] <= 1e-3, (
        f"clk_fb period off by {measures['fb_period_rel_err']:.2e}")
    assert measures["vco_period_rel_err"] <= 1e-3, (
        f"vco_out period off by {measures['vco_period_rel_err']:.2e}")
    assert measures["vctrl_pp_last_10us_mv"] <= 20, (
        f"vctrl moved {measures['vctrl_pp_last_10us_mv']:.1f} mV p-p in the last 10 us")
